import assert from 'node:assert/strict';
import {splitSource,numbersPreserved,negativeMeaningNotDropped,validateTranslation} from './analysts-translation.mjs';
assert.deepEqual(splitSource('שלום'),['שלום']);
const long='A sentence. '.repeat(460);
const parts=splitSource(long);
assert.ok(parts.length>1&&parts.length<=6);
assert.equal(parts.join(' '),long.trim());
assert.ok(parts.every(x=>x.length<=1350));
assert.ok(numbersPreserved('5 aircraft and 12 flights','5 самолётов и 12 рейсов'));
assert.ok(!numbersPreserved('5 aircraft and 12 flights','5 самолётов и 21 рейс'));
assert.equal(negativeMeaningNotDropped('לא אושרה תקיפה באיראן','Удар по Ирану не подтверждён','he'),true);
assert.equal(negativeMeaningNotDropped('לא אושרה תקיפה באיראן','Удар по Ирану подтверждён','he'),false);
assert.equal(negativeMeaningNotDropped('No airstrikes reported','О налётах не сообщается','en'),true);
const original='לא אושרה תקיפה באיראן 2026';
const good={translation:'Удар по Ирану в 2026 году официально не подтверждён.',confidence:91,issues:[]};
assert.ok(validateTranslation(original,good,'he'));
assert.equal(validateTranslation(original,{...good,confidence:0.91},'he')?.confidence,91);
assert.equal(validateTranslation(original,{...good,confidence:0.5},'he'),null);
assert.equal(validateTranslation(original,{...good,translation:'Удар по Ирану в 2027 году подтверждён.'},'he'),null);
assert.equal(validateTranslation(original,{...good,confidence:65},'he'),null);
assert.equal(validateTranslation(original,{...good,issues:['ambiguous name']},'he'),null);
console.log('analyst multilingual translation checks: OK');
