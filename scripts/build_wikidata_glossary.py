#!/usr/bin/env python3
"""B11 part 1: build the Wikidata part of the translation glossary.

Reads config/glossary-wikidata.json (entity id + English Wikipedia title),
fetches labels and aliases in en/ru/he from the Wikidata API in one request
per 50 titles (wbgetentities by enwiki title: no search ambiguity), filters
forms that would make the check noisy, and writes
backend/editor/src/translations/glossary-wikidata.mjs. The Editor never calls
Wikidata at run time; the file is regenerated by .github/workflows/wikidata-glossary.yml.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config/glossary-wikidata.json"
OUTPUT = ROOT / "backend/editor/src/translations/glossary-wikidata.mjs"
API = "https://www.wikidata.org/w/api.php"
USER_AGENT = "regional-osint-feeds glossary builder (+https://github.com/ArrakturIL/regional-osint-feeds)"
LANGS = ("en", "ru", "he")
MAX_FORMS = 10
HEBREW = re.compile(r"[֐-׿]")
CYRILLIC = re.compile(r"[Ѐ-ӿ]")
LATIN = re.compile(r"[A-Za-z]")
NIQQUD = re.compile(r"[֑-ׇ]")


def load_config(path: Path = CONFIG) -> list[tuple[str, str]]:
    cfg = json.loads(Path(path).read_text(encoding="utf8"))
    if cfg.get("schema_version") != 1:
        raise ValueError("invalid glossary config schema")
    entities = [(e[0], e[1], tuple(e[2]) if len(e) > 2 else ()) for e in cfg["entities"]]
    ids = [e[0] for e in entities]
    if len(set(ids)) != len(ids) or not all(re.fullmatch(r"[a-z][a-z0-9_]*", i) for i in ids):
        raise ValueError("entity ids must be unique snake_case")
    return entities


def fetch(titles: list[str], opener=urllib.request.urlopen) -> dict:
    # One title: normalize=1 also resolves a moved/redirected article title.
    extra = {"normalize": "1"} if len(titles) == 1 else {}
    query = urllib.parse.urlencode({
        **extra,
        "action": "wbgetentities", "sites": "enwiki", "titles": "|".join(titles),
        "props": "labels|aliases|sitelinks", "sitefilter": "enwiki", "languages": "|".join(LANGS),
        "format": "json",
    })
    req = urllib.request.Request(API + "?" + query, headers={"User-Agent": USER_AGENT})
    for attempt in range(4):
        try:
            with opener(req, timeout=30) as response:
                return json.loads(response.read())
        except urllib.error.HTTPError as exc:
            if exc.code != 429 or attempt == 3:
                raise
            time.sleep(5 * (attempt + 1))
    raise RuntimeError("unreachable")


def clean(form: str) -> str:
    form = unicodedata.normalize("NFC", NIQQUD.sub("", form)).strip()
    return re.sub(r"\s+", " ", form)


def keep(form: str, lang: str) -> bool:
    """Forms that identify the entity without matching ordinary words."""
    if not form or "(" in form or re.search(r"\d", form) or len(form) > 60:
        return False
    if lang == "en":
        if not LATIN.search(form) or form.lower().startswith("the "):
            return False
        letters = re.sub(r"[^A-Za-z]", "", form)
        # Short forms only as acronyms (matched case-sensitively): US, UN, EU.
        return len(letters) >= 4 or (form.isupper() and len(letters) >= 2)
    if lang == "ru":
        return bool(CYRILLIC.search(form)) and not LATIN.search(form) and len(re.sub(r"[^\w]", "", form)) >= 3
    return bool(HEBREW.search(form)) and not LATIN.search(form) and len(HEBREW.findall(form)) >= 3


def forms_for(entity: dict) -> dict[str, list[str]]:
    out = {}
    for lang in LANGS:
        values = []
        label = entity.get("labels", {}).get(lang, {}).get("value")
        if label:
            values.append(label)
        values += [a["value"] for a in entity.get("aliases", {}).get(lang, [])]
        seen, result = set(), []
        for v in map(clean, values):
            if keep(v, lang) and v.lower() not in seen:
                seen.add(v.lower())
                result.append(v)
        out[lang] = result[:MAX_FORMS]
    return out


def build(entities: list[tuple], fetcher=fetch) -> list[dict]:
    by_title, normalized = {}, {}
    for i in range(0, len(entities), 50):
        chunk = entities[i:i + 50]
        data = fetcher([t for _, t, _ in chunk])
        normalized.update({n["from"]: n["to"] for n in data.get("normalized", [])})
        if "error" in data:
            raise RuntimeError("Wikidata API error: " + str(data["error"].get("code")))
        for qid, entity in data.get("entities", {}).items():
            if not qid.startswith("Q"):
                continue
            title = entity.get("sitelinks", {}).get("enwiki", {}).get("title")
            if title:
                by_title[title] = (qid, entity)
        for _, title, _ in chunk:
            if normalized.get(title, title) in by_title:
                continue
            # Redirected title: ask for it alone, keep the item under the asked title.
            single = fetcher([title])
            found = [(q, e) for q, e in single.get("entities", {}).items() if q.startswith("Q")]
            if len(found) != 1:
                raise ValueError("no Wikidata item for enwiki title: " + title)
            by_title[title] = found[0]
        if i + 50 < len(entities):
            time.sleep(1)
    result = []
    for entity_id, title, exclude in entities:
        qid, entity = by_title[normalized.get(title, title)]
        forms = forms_for(entity)
        forms = {lang: [f for f in v if f not in exclude] for lang, v in forms.items()}
        missing = [lang for lang in LANGS if not forms[lang]]
        if missing:
            # Without RU and HE forms the check could only fail: skip, visibly.
            print(f"::warning::{entity_id} ({qid}) skipped: no usable form in {missing}")
            continue
        result.append({"id": entity_id, "qid": qid, **forms})
    return result


def render(entities: list[dict], generated_at: str) -> str:
    body = json.dumps(entities, ensure_ascii=False, indent=1)
    return (
        "// GENERATED by scripts/build_wikidata_glossary.py from Wikidata (labels and\n"
        "// aliases, CC0). Do not edit by hand: change config/glossary-wikidata.json.\n"
        f"// Generated {generated_at}.\n"
        f"export const WIKIDATA_ENTITIES = {body};\n"
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", default=str(OUTPUT))
    args = parser.parse_args(argv)
    entities = build(load_config())
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    Path(args.output).write_text(render(entities, stamp), encoding="utf8")
    print(f"wikidata_glossary entities={len(entities)} output={args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
